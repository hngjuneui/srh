import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const require=createRequire(import.meta.url);
const { chromium }=require(process.env.PLAYWRIGHT_PATH || 'C:/Users/USER/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const browser=await chromium.launch({headless:true,channel:'chrome',args:['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream']});
const context=await browser.newContext({viewport:{width:1440,height:1080},permissions:['camera']});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
fs.mkdirSync('test-results',{recursive:true});
execFileSync(path.resolve('.venv/Scripts/python.exe'),['scripts/make_fixture.py']);
try{
  await page.goto(process.env.RALLY_BASE_URL || 'http://127.0.0.1:8765');
  await page.locator('#accessCode').fill(fs.readFileSync('data/access-code.txt','utf8').trim());
  await page.locator('#loginForm button').click();
  await page.locator('#loginDialog').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.querySelector('#serverPill').classList.contains('connected'));
  // Each run uses a new session; previous recordings or scores are never modified.
  await page.locator('#newSession').click();
  await page.waitForFunction(()=>document.querySelector('#scoreA').textContent==='0'&&document.querySelector('#scoreB').textContent==='0');
  await page.screenshot({path:'test-results/desktop-analysis.png',fullPage:true});
  await page.locator('.segmented [data-mode=score]').click();
  await page.locator('[data-point=B]').click();
  await page.waitForFunction(()=>document.querySelector('#scoreB').textContent==='1');
  await page.locator('#flipPoint').click();
  await page.waitForFunction(()=>document.querySelector('#scoreA').textContent==='1'&&document.querySelector('#scoreB').textContent==='0');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#scoreA').textContent==='1');
  await page.locator('.segmented [data-mode=score]').click();
  await page.locator('#settingsOpen2').click();
  await page.locator('[name=last_hit]').check();
  await page.locator('[name=fusion]').selectOption('single');
  await page.locator('#settingsForm button[type=submit]').click();
  await page.locator('#settingsDialog').waitFor({state:'hidden'});
  await page.screenshot({path:'test-results/desktop-score.png',fullPage:true});
  await page.locator('#startCamera').click();
  await page.waitForFunction(()=>document.querySelector('#frameLabel').textContent.startsWith('#'),{timeout:45000});
  await page.waitForFunction(()=>!document.querySelector('#fpsValue').textContent.includes('—'));
  await page.screenshot({path:'test-results/live-analysis.png',fullPage:true});
  const diagnostics=await page.locator('.telemetry').innerText();
  await page.locator('#stopButton').click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/mobile-score.png',fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile horizontal overflow');
  await page.locator('.segmented [data-mode=analysis]').click();
  await page.screenshot({path:'test-results/mobile-analysis.png',fullPage:true});
  await page.locator('#settingsOpen2').click();
  await page.screenshot({path:'test-results/mobile-settings.png',fullPage:true});
  await page.locator('[data-close=settingsDialog]').click();
  await page.locator('#videoFile').setInputFiles('test-results/input.mp4');
  await page.waitForFunction(()=>document.querySelector('#uploadText').textContent.startsWith('분석 완료'),null,{timeout:60000});
  await page.waitForFunction(()=>Number.isFinite(document.querySelector('#video').duration));
  await page.locator('#addClip').click();
  await page.locator('[data-start="0"]').fill('0.2');
  await page.locator('[data-end="0"]').fill('1.4');
  await page.locator('#playClips').click();
  await page.waitForFunction(()=>!document.querySelector('#video').paused);
  const downloadPromise=page.waitForEvent('download',{timeout:60000});
  await page.locator('#exportClips').click();
  const download=await downloadPromise;
  await download.saveAs('test-results/ui-highlights.mp4');
  if(fs.statSync('test-results/ui-highlights.mp4').size<1000)throw new Error('Export is empty');
  await page.screenshot({path:'test-results/mobile-highlights.png',fullPage:true});
  await page.locator('#undoPoint').evaluate(e=>e.click());
  console.log(JSON.stringify({passed:true,browserErrors:errors,diagnostics,screenshots:'test-results'},null,2));
  if(errors.length)throw new Error(errors.join('\n'));
}finally{await browser.close();}
